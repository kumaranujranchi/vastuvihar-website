// Converts the Lightsail SQLite database (Prisma on Node.js) into SQL for a freshly
// migrated D1 database. Read-only on the source.
//
//   node --experimental-sqlite scripts/export-sqlite-to-d1.mjs <lightsail.db> <out.sql> [--include-sessions]
//
// Why not a plain `.dump`: Prisma on Node.js stores DateTime as integer milliseconds,
// but Prisma's D1 adapter stores and expects ISO text ("2026-11-19T13:30:29.550+00:00").
// An integer date makes the D1 adapter throw "Inconsistent column data" on read, and
// breaks date comparisons. This script rewrites every DateTime column to that ISO form.
//
// Skipped by default: AdminSession (everyone signs in again on Cloudflare) and
// RateLimitHit (short-lived). Columns are copied only where both the source table and
// the Prisma schema have them, so drift from `prisma db push` is reported, not fatal.
import fs from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const [source, output, ...flags] = process.argv.slice(2);
if (!source || !output) {
  console.error('Usage: node --experimental-sqlite scripts/export-sqlite-to-d1.mjs <lightsail.db> <out.sql> [--include-sessions]');
  process.exit(1);
}
if (!fs.existsSync(source)) {
  console.error(`Not found: ${source}`);
  process.exit(1);
}

let DatabaseSync;
try {
  ({ DatabaseSync } = require('node:sqlite'));
} catch {
  console.error('Needs Node.js 22.5 or later, run with --experimental-sqlite.');
  process.exit(1);
}
const { Prisma } = require('@prisma/client');

const SKIP = new Set(['RateLimitHit', ...(flags.includes('--include-sessions') ? [] : ['AdminSession'])]);
const models = Prisma.dmmf.datamodel.models;
const byName = new Map(models.map((model) => [model.dbName || model.name, model]));

// Parents before children, so the import order also reads naturally.
const order = [];
const visit = (model, seen = new Set()) => {
  if (order.includes(model) || seen.has(model)) return;
  seen.add(model);
  for (const field of model.fields) {
    if (field.kind === 'object' && field.relationFromFields?.length) {
      const parent = models.find((candidate) => candidate.name === field.type);
      if (parent) visit(parent, seen);
    }
  }
  order.push(model);
};
models.forEach((model) => visit(model));

/** The D1 adapter's DateTime format: millisecond ISO with an explicit +00:00 offset. */
function isoDate(value) {
  if (value === null || value === undefined) return null;
  let date;
  if (typeof value === 'number' || typeof value === 'bigint') date = new Date(Number(value));
  else if (/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}(\.\d+)?$/.test(value)) date = new Date(`${value.replace(' ', 'T')}Z`);
  else if (/^\d+$/.test(value)) date = new Date(Number(value));
  else date = new Date(value);
  if (Number.isNaN(date.getTime())) throw new Error(`Unreadable date: ${value}`);
  return date.toISOString().replace('Z', '+00:00');
}

function literal(value) {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number' || typeof value === 'bigint') return String(value);
  if (typeof value === 'boolean') return value ? '1' : '0';
  if (value instanceof Uint8Array) return `X'${Buffer.from(value).toString('hex')}'`;
  return `'${String(value).replaceAll("'", "''")}'`;
}

const db = new DatabaseSync(source, { readOnly: true });
const tables = new Set(
  db.prepare("SELECT name FROM sqlite_master WHERE type = 'table'").all().map((row) => row.name),
);

const lines = [
  '-- Generated by scripts/export-sqlite-to-d1.mjs. Import into an EMPTY, fully migrated D1:',
  '--   npx wrangler d1 execute DB --remote [--env uat] --file <this file>',
  `-- Source: ${source.split(/[\\/]/).pop()}  Generated: ${new Date().toISOString()}`,
  'PRAGMA defer_foreign_keys = true;',
];
const report = [];
let problems = 0;

for (const model of order) {
  const table = model.dbName || model.name;
  if (SKIP.has(table)) {
    report.push({ table, rows: 'skipped' });
    continue;
  }
  if (!tables.has(table)) {
    report.push({ table, rows: 'not in source' });
    continue;
  }
  const scalar = model.fields.filter((field) => field.kind === 'scalar' || field.kind === 'enum');
  const sourceColumns = new Set(db.prepare(`PRAGMA table_info("${table}")`).all().map((column) => column.name));
  const columns = scalar.filter((field) => sourceColumns.has(field.dbName || field.name));
  const missing = scalar.filter((field) => !sourceColumns.has(field.dbName || field.name));
  const extra = [...sourceColumns].filter((name) => !scalar.some((field) => (field.dbName || field.name) === name));
  for (const field of missing) {
    // A required column with no default would make every insert fail.
    if (field.isRequired && !field.hasDefaultValue && !field.isUpdatedAt) {
      console.error(`ERROR ${table}.${field.name} is required but missing from the source.`);
      problems += 1;
    }
  }

  const names = columns.map((field) => field.dbName || field.name);
  const rows = db.prepare(`SELECT ${names.map((name) => `"${name}"`).join(', ')} FROM "${table}"`).all();
  const fill = missing.filter((field) => field.isUpdatedAt);
  for (const row of rows) {
    const values = columns.map((field) => {
      const value = row[field.dbName || field.name];
      return literal(field.type === 'DateTime' ? isoDate(value) : value);
    });
    const now = literal(isoDate(Date.now()));
    const allNames = [...names, ...fill.map((field) => field.dbName || field.name)];
    const allValues = [...values, ...fill.map(() => now)];
    lines.push(`INSERT INTO "${table}" (${allNames.map((name) => `"${name}"`).join(', ')}) VALUES (${allValues.join(', ')});`);
  }
  report.push({
    table,
    rows: rows.length,
    ...(missing.length ? { missingInSource: missing.map((field) => field.name).join(',') } : {}),
    ...(extra.length ? { notCopied: extra.join(',') } : {}),
  });
}
db.close();

fs.writeFileSync(output, `${lines.join('\n')}\n`, { mode: 0o600 });
console.table(report);
console.log(`Wrote ${lines.length - 4} INSERT statements to ${output}. It holds personal data: keep it private and delete it after the import.`);
if (problems) {
  console.error(`${problems} blocking problem(s). Fix the source schema before importing.`);
  process.exit(1);
}
